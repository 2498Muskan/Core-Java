
public class forcase2 {
    public static void main(String[] args) {
        for(int i=1; i<=40; i++){
            System.out.println("\nMultiplication Table of " + i);

            for(int j=1; j<=10; j++){
                System.out.println(i + " x " + j + " = " + (i*j));
            }
        }
    }
}
